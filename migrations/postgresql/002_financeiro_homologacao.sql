CREATE TABLE IF NOT EXISTS planos_assinatura (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo TEXT NOT NULL UNIQUE,
 nome TEXT NOT NULL,
 periodo_meses INTEGER NOT NULL CHECK(periodo_meses > 0),
 preco_centavos INTEGER NOT NULL CHECK(preco_centavos >= 0),
 ativo INTEGER NOT NULL DEFAULT 1 CHECK(ativo IN (0,1))
);
INSERT INTO planos_assinatura (codigo, nome, periodo_meses, preco_centavos, ativo)
VALUES ('mensal','Mensal',1,5000,1),
       ('trimestral','Trimestral',3,12000,1),
       ('semestral','Semestral',6,25000,1)
ON CONFLICT (codigo) DO NOTHING;

CREATE TABLE IF NOT EXISTS cobrancas_assinatura (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assinatura_id BIGINT NOT NULL REFERENCES assinaturas_personais(id),
 plano_id BIGINT NOT NULL REFERENCES planos_assinatura(id),
 referencia TEXT NOT NULL UNIQUE,
 valor_centavos INTEGER NOT NULL CHECK(valor_centavos > 0),
 periodo_meses INTEGER NOT NULL CHECK(periodo_meses > 0),
 status TEXT NOT NULL DEFAULT 'pendente'
  CHECK(status IN ('pendente','paga','cancelada','expirada')),
 identificador_externo TEXT UNIQUE,
 criada_em TEXT NOT NULL,
 paga_em TEXT,
 valor_original_centavos INTEGER,
 desconto_centavos INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS cupons_assinatura (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo TEXT NOT NULL UNIQUE,
 desconto_centavos INTEGER NOT NULL CHECK(desconto_centavos > 0),
 personal_id BIGINT,
 plano_id BIGINT,
 ativo INTEGER NOT NULL DEFAULT 1 CHECK(ativo IN (0,1)),
 usado_em TEXT,
 cobranca_id BIGINT UNIQUE,
 administrador_id BIGINT
);

CREATE TABLE IF NOT EXISTS orders_mercado_pago (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cobranca_id BIGINT NOT NULL UNIQUE REFERENCES cobrancas_assinatura(id),
 order_id TEXT NOT NULL UNIQUE,
 status TEXT NOT NULL,
 criada_em TEXT NOT NULL,
 atualizada_em TEXT NOT NULL
);
COMMIT;
