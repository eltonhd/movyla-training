BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome TEXT NOT NULL,
 usuario TEXT NOT NULL UNIQUE,
 senha TEXT NOT NULL,
 tipo TEXT NOT NULL DEFAULT 'aluno',
 ativo INTEGER NOT NULL DEFAULT 1,
 foto TEXT,
 responsavel_id BIGINT,
 email TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_email_unico
 ON usuarios (LOWER(email)) WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS exercicios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome TEXT NOT NULL,
 grupo_muscular TEXT NOT NULL,
 equipamento TEXT,
 repeticoes_min INTEGER,
 repeticoes_max INTEGER,
 incremento_carga DOUBLE PRECISION,
 video_url TEXT,
 responsavel_id BIGINT
);
CREATE TABLE IF NOT EXISTS treinos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome TEXT NOT NULL,
 descricao TEXT,
 dia_semana INTEGER,
 responsavel_id BIGINT
);
CREATE TABLE IF NOT EXISTS treino_exercicios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treino_id BIGINT NOT NULL REFERENCES treinos(id),
 exercicio_id BIGINT NOT NULL REFERENCES exercicios(id),
 ordem INTEGER NOT NULL,
 progressao TEXT NOT NULL DEFAULT 'automatica',
 incremento DOUBLE PRECISION NOT NULL DEFAULT 2.5
);
CREATE TABLE IF NOT EXISTS sessoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treino_id BIGINT NOT NULL REFERENCES treinos(id),
 data TEXT NOT NULL,
 usuario_id BIGINT
);
CREATE TABLE IF NOT EXISTS series (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sessao_id BIGINT NOT NULL REFERENCES sessoes(id),
 exercicio_id BIGINT NOT NULL REFERENCES exercicios(id),
 numero_serie INTEGER NOT NULL,
 carga DOUBLE PRECISION NOT NULL,
 repeticoes INTEGER NOT NULL,
 rir DOUBLE PRECISION,
 rpe DOUBLE PRECISION,
 observacoes TEXT,
 treino_exercicio_id BIGINT
);
CREATE TABLE IF NOT EXISTS treino_alunos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 treino_id BIGINT NOT NULL REFERENCES treinos(id),
 dia_semana INTEGER,
 UNIQUE(usuario_id, treino_id)
);
CREATE TABLE IF NOT EXISTS treino_series (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treino_exercicio_id BIGINT NOT NULL REFERENCES treino_exercicios(id) ON DELETE CASCADE,
 numero_serie INTEGER NOT NULL,
 repeticoes_prescritas INTEGER
);
CREATE TABLE IF NOT EXISTS treino_aluno_series (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treino_aluno_id BIGINT NOT NULL REFERENCES treino_alunos(id),
 treino_exercicio_id BIGINT NOT NULL REFERENCES treino_exercicios(id),
 numero_serie INTEGER NOT NULL,
 repeticoes_prescritas INTEGER
);
CREATE TABLE IF NOT EXISTS assinaturas_personais (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 personal_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id),
 plano TEXT NOT NULL,
 valor_mensal DOUBLE PRECISION NOT NULL DEFAULT 0,
 data_inicio TEXT,
 proximo_vencimento TEXT,
 isento INTEGER NOT NULL DEFAULT 0,
 motivo_isencao TEXT,
 observacoes TEXT,
 tipo_assinatura TEXT NOT NULL DEFAULT 'paga',
 periodo_quantidade INTEGER,
 periodo_unidade TEXT
);
CREATE TABLE IF NOT EXISTS pagamentos_personais (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assinatura_id BIGINT NOT NULL REFERENCES assinaturas_personais(id),
 competencia TEXT NOT NULL,
 valor_pago DOUBLE PRECISION NOT NULL,
 data_pagamento TEXT NOT NULL,
 forma_pagamento TEXT,
 observacoes TEXT
);
CREATE TABLE IF NOT EXISTS recuperacao_senha (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 token_hash TEXT NOT NULL UNIQUE,
 expira_em TEXT NOT NULL,
 utilizado_em TEXT,
 criado_em TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::TEXT)
);
COMMIT;
